// 01 - Keywords, Reserved Words and Identifiers

// JavaScript keywords have special meanings.
// Examples: let, const, var, if, else, switch, function, return

let studentName = "Rahul";
const courseName = "JavaScript";

let isPass = true;
let place = "Bangalore";

console.log(typeof isPass);
console.log(typeof place);

console.log(studentName);
console.log(courseName);

// Valid identifiers can contain letters, digits, _ and $.
// They cannot start with a digit.

// Examples of valid identifiers:
// studentName
// student1
// _count
// $price

